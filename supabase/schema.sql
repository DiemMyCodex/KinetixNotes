create table if not exists public.lessons (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users (id) on delete set null,
  category text not null check (category in ('Máy tính', 'Trí tuệ AI', 'Tâm lý & Sống', 'Kinh tế')),
  title text not null,
  summary text not null,
  points jsonb not null default '[]'::jsonb,
  quiz text not null,
  answer text not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_lessons_category on public.lessons (category);
create index if not exists idx_lessons_created_at on public.lessons (created_at desc);

alter table public.lessons enable row level security;

drop policy if exists "Anyone can read lessons" on public.lessons;
drop policy if exists "Public read access for lessons" on public.lessons;
create policy "Anyone can read lessons"
  on public.lessons
  for select
  using (true);

drop policy if exists "Authenticated users can insert their own lessons" on public.lessons;
drop policy if exists "Only admin can insert lessons" on public.lessons;
create policy "Only admin can insert lessons"
  on public.lessons
  for insert
  to authenticated
  with check (
    auth.uid() = user_id
    and lower(coalesce(auth.jwt() ->> 'email', '')) = 'diemmycodex@gmail.com'
  );

drop policy if exists "Users can update their own lessons" on public.lessons;
drop policy if exists "Only admin can update lessons" on public.lessons;
create policy "Only admin can update lessons"
  on public.lessons
  for update
  to authenticated
  using (
    auth.uid() = user_id
    and lower(coalesce(auth.jwt() ->> 'email', '')) = 'diemmycodex@gmail.com'
  )
  with check (
    auth.uid() = user_id
    and lower(coalesce(auth.jwt() ->> 'email', '')) = 'diemmycodex@gmail.com'
  );

drop policy if exists "Users can delete their own lessons" on public.lessons;
drop policy if exists "Only admin can delete lessons" on public.lessons;
create policy "Only admin can delete lessons"
  on public.lessons
  for delete
  to authenticated
  using (
    auth.uid() = user_id
    and lower(coalesce(auth.jwt() ->> 'email', '')) = 'diemmycodex@gmail.com'
  );

create table if not exists public.user_progress (
  user_id uuid not null references auth.users (id) on delete cascade,
  lesson_id bigint not null,
  created_at timestamptz not null default now(),
  primary key (user_id, lesson_id)
);

create index if not exists idx_user_progress_user_id on public.user_progress (user_id);
create index if not exists idx_user_progress_lesson_id on public.user_progress (lesson_id);

alter table public.user_progress enable row level security;

drop policy if exists "Users can view their own progress" on public.user_progress;
create policy "Users can view their own progress"
  on public.user_progress
  for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users can insert their own progress" on public.user_progress;
create policy "Users can insert their own progress"
  on public.user_progress
  for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "Users can update their own progress" on public.user_progress;
create policy "Users can update their own progress"
  on public.user_progress
  for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Users can delete their own progress" on public.user_progress;
create policy "Users can delete their own progress"
  on public.user_progress
  for delete
  to authenticated
  using (auth.uid() = user_id);
